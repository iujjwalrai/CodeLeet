const fs = require("fs");
const path = require("path");
const { TYPES, javaIo, cppParam } = require("./types");

/*
 * Builds the C++ and Java drivers and starter code for a function signature
 * { name, params: [{ name, type }], returns } (see types.js).
 *
 * C++: Main.cpp = prelude.hpp + cl_io.hpp + #include "Solution.cpp" + main.
 *   Compiled as one unit, so the user's class sees the headers and
 *   ListNode/TreeNode, and compiler errors still name Solution.cpp.
 * Java: Main.java = imports + CodeleetIO.java (ListNode, TreeNode, IO) + Main,
 *   compiled together with Solution.java.
 */

const runtime = (file) => fs.readFileSync(path.join(__dirname, "runtime", file), "utf8");

const HEADER = "// Generated by problemkit/codegen.js from the problem's signature. Do not edit.";

const uses = (sig, type) => sig.returns === type || sig.params.some((p) => p.type === type);

const CPP_DOCS = {
  ListNode: [
    "/**",
    " * Definition for singly-linked list.",
    " * struct ListNode {",
    " *     int val;",
    " *     ListNode *next;",
    " *     ListNode() : val(0), next(nullptr) {}",
    " *     ListNode(int x) : val(x), next(nullptr) {}",
    " *     ListNode(int x, ListNode *next) : val(x), next(next) {}",
    " * };",
    " */",
  ],
  TreeNode: [
    "/**",
    " * Definition for a binary tree node.",
    " * struct TreeNode {",
    " *     int val;",
    " *     TreeNode *left;",
    " *     TreeNode *right;",
    " *     TreeNode() : val(0), left(nullptr), right(nullptr) {}",
    " *     TreeNode(int x) : val(x), left(nullptr), right(nullptr) {}",
    " *     TreeNode(int x, TreeNode *left, TreeNode *right) : val(x), left(left), right(right) {}",
    " * };",
    " */",
  ],
};

const JAVA_DOCS = {
  ListNode: [
    "/**",
    " * Definition for singly-linked list.",
    " * class ListNode {",
    " *     int val;",
    " *     ListNode next;",
    " *     ListNode() {}",
    " *     ListNode(int val) { this.val = val; }",
    " *     ListNode(int val, ListNode next) { this.val = val; this.next = next; }",
    " * }",
    " */",
  ],
  TreeNode: [
    "/**",
    " * Definition for a binary tree node.",
    " * class TreeNode {",
    " *     int val;",
    " *     TreeNode left;",
    " *     TreeNode right;",
    " *     TreeNode() {}",
    " *     TreeNode(int val) { this.val = val; }",
    " *     TreeNode(int val, TreeNode left, TreeNode right) { this.val = val; this.left = left; this.right = right; }",
    " * }",
    " */",
  ],
};

const docsFor = (sig, docs) =>
  ["ListNode", "TreeNode"].filter((t) => uses(sig, t)).flatMap((t) => [...docs[t], ""]);

function cppStarter(sig) {
  const params = sig.params.map((p) => cppParam(p.type, p.name)).join(", ");
  return [
    ...docsFor(sig, CPP_DOCS),
    "class Solution {",
    "public:",
    `    ${TYPES[sig.returns].cpp} ${sig.name}(${params}) {`,
    "        ",
    "    }",
    "};",
    "",
  ].join("\n");
}

function javaStarter(sig) {
  const params = sig.params.map((p) => `${TYPES[p.type].java} ${p.name}`).join(", ");
  return [
    "import java.util.*;",
    "",
    ...docsFor(sig, JAVA_DOCS),
    "class Solution {",
    `    public ${TYPES[sig.returns].java} ${sig.name}(${params}) {`,
    "        ",
    "    }",
    "}",
    "",
  ].join("\n");
}

// Locals in main are prefixed so they can't collide with a parameter name
const arg = (i) => `cl_arg${i}`;

const cppPrefix = () => [HEADER, runtime("prelude.hpp"), runtime("cl_io.hpp")].join("\n");

function cppDriver(sig) {
  return [
    cppPrefix(),
    '#include "Solution.cpp"',
    "",
    // `signed`, not `int`: Solution.cpp may `#define int long long`
    "signed main() {",
    "    cl_io::Reader in;",
    ...sig.params.map((p, i) => `    auto ${arg(i)} = in.read${TYPES[p.type].io}();`),
    "    Solution solution;",
    `    auto result = solution.${sig.name}(${sig.params.map((_, i) => arg(i)).join(", ")});`,
    "    cl_io::Writer out;",
    `    out.write${TYPES[sig.returns].io}(result);`,
    "    out.flush();",
    "}",
    "",
  ].join("\n");
}

const javaPrefix = () =>
  [
    HEADER,
    "import java.nio.charset.StandardCharsets;",
    "import java.util.List;",
    "",
    runtime("CodeleetIO.java"),
  ].join("\n");

// Prints the output collected by `body` (which fills StringBuilder out)
const javaMain = (reads, body) => [
  "public class Main {",
  "    public static void main(String[] args) throws Exception {",
  "        CodeleetIO in = new CodeleetIO(System.in.readAllBytes());",
  ...reads,
  "        StringBuilder out = new StringBuilder();",
  "        Throwable[] error = new Throwable[1];",
  "        // A big stack, so deep recursion behaves as it does in C++",
  "        Thread solver = new Thread(null, () -> {",
  ...body,
  '        }, "solution", 256L << 20);',
  "        solver.setUncaughtExceptionHandler((t, e) -> error[0] = e);",
  "        solver.start();",
  "        solver.join();",
  "        if (error[0] != null) {",
  "            error[0].printStackTrace();",
  "            System.exit(1);",
  "        }",
  "        out.append('\\n');",
  "        System.out.write(out.toString().getBytes(StandardCharsets.UTF_8));",
  "        System.out.flush();",
  "    }",
  "}",
  "",
];

function javaDriver(sig) {
  const reads = sig.params.map((p, i) => `        final ${TYPES[p.type].java} ${arg(i)} = in.read${TYPES[p.type].io}();`);
  const call = `new Solution().${sig.name}(${sig.params.map((_, i) => arg(i)).join(", ")})`;
  return [javaPrefix(), ...javaMain(reads, [`            CodeleetIO.write${javaIo(sig.returns)}(out, ${call});`])].join("\n");
}

/*
 * Drivers that read one value of each type and print it straight back, one
 * per line. The seed script runs them before anything else to check that
 * both runtimes read and write every type the same way.
 */
function cppEchoDriver(types) {
  return [
    cppPrefix(),
    "signed main() {",
    "    cl_io::Reader in;",
    "    cl_io::Writer out;",
    ...types.flatMap((t, i) => [
      `    auto ${arg(i)} = in.read${TYPES[t].io}();`,
      `    out.write${TYPES[t].io}(${arg(i)});`,
      i < types.length - 1 ? "    out.line();" : "    out.flush();",
    ]),
    "}",
    "",
  ].join("\n");
}

function javaEchoDriver(types) {
  const reads = types.map((t, i) => `        final ${TYPES[t].java} ${arg(i)} = in.read${javaIo(t)}();`);
  const body = types.flatMap((t, i) => [
    `            CodeleetIO.write${javaIo(t)}(out, ${arg(i)});`,
    ...(i < types.length - 1 ? ["            out.append('\\n');"] : []),
  ]);
  return [javaPrefix(), ...javaMain(reads, body)].join("\n");
}

/* A generator's full source: the gen.hpp helpers, then the problem's code */
const generatorSource = (code) => `${runtime("gen.hpp")}${code}`;

module.exports = { cppStarter, javaStarter, cppDriver, javaDriver, cppEchoDriver, javaEchoDriver, generatorSource };
